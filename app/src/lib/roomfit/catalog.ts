export function searchCatalog(query: string, category = '') {
  const aliases: Record<string,string> = {'电脑桌':'电竞桌','电竞椅':'椅','gaming desk':'gaming desk','沙發':'沙发','desk gaming':'gaming desk','书柜':'书架','pc case':'pc','rgb灯':'rgb'};
  const q = (aliases[query.toLowerCase().trim()] || query).toLowerCase().trim();
  const words = q.split(/\s+/).filter(Boolean);
  return catalog.filter(f => (!category || f.category===category) && words.every(word => `${f.name} ${f.en} ${f.id} ${f.category} ${f.style}`.toLowerCase().includes(word)));
}
